// Classic-design editor: drag with branch, Alt single-card drag, undo/redo/reset, save + reopen project.
import { readFileSync } from 'node:fs';
import { chromium, open, ok, tab } from './lib.mjs';
const b = await chromium.launch(); const pg = await b.newPage({ viewport: { width: 1500, height: 950 }, acceptDownloads: true });
const errs = await open(pg);
await tab(pg, 'tree'); await pg.check('#relatives'); await pg.check('#siblings'); await pg.selectOption('#gens', '4');
await tab(pg, 'style'); await pg.selectOption('#design', 'classic'); await pg.selectOption('#card', 'compact');
await pg.fill('#zoom', '60'); await pg.dispatchEvent('#zoom', 'input'); await tab(pg, 'edit');
const tf = () => pg.$$eval('.card', (g) => g.map((x) => x.getAttribute('transform')));
const clash = async () => { await tab(pg, 'export'); const t = (await pg.textContent('#info')).match(/(\d+) overlapping lines, (\d+) overlapping cards/).slice(1).map(Number); await tab(pg, 'edit'); return t; };
const base = await tf(); console.log('cards', base.length, 'start clashes', await clash());
const drag = async (i, dx, dy, alt) => {
  await pg.locator(`.card[data-i="${i}"]`).scrollIntoViewIfNeeded();
  const r = await pg.locator(`.card[data-i="${i}"] rect`).first().boundingBox();
  if (alt) await pg.keyboard.down('Alt');
  await pg.mouse.move(r.x + r.width / 2, r.y + r.height / 2); await pg.mouse.down();
  await pg.mouse.move(r.x + r.width / 2 + dx / 2, r.y + r.height / 2 + dy / 2, { steps: 4 }); await pg.mouse.move(r.x + r.width / 2 + dx, r.y + r.height / 2 + dy, { steps: 4 });
  await pg.mouse.up(); if (alt) await pg.keyboard.up('Alt'); await pg.waitForTimeout(150);
};
await drag(1, 0, 120, false);
let after = await tf(); const changed = after.filter((t, i) => t !== base[i]).length;
ok(changed > 1, `dragging a lineage card moved its branch (${changed} cards moved)`);
ok(changed < base.length, 'cards outside the branch stayed put');
ok((await clash()).join() === '0,0', 'no overlaps after the drag');
await pg.click('#undo'); ok((await tf()).every((t, i) => t === base[i]), 'undo restores every card');
await pg.click('#redo'); ok((await tf()).filter((t, i) => t !== base[i]).length === changed, 'redo reapplies the move');
await pg.click('#reset'); ok((await tf()).every((t, i) => t === base[i]), 'reset layout');
await pg.click('#undo');
const a2 = (await tf()).slice();
await drag(1, 0, 60, true);
const single = (await tf()).filter((t, i) => t !== a2[i]).length; ok(single === 1, `Alt-drag moves one card (${single})`);
await tab(pg, 'export');
const [dl] = await Promise.all([pg.waitForEvent('download'), pg.click('#save')]); await dl.saveAs('/tmp/proj.json');
const proj = JSON.parse(readFileSync('/tmp/proj.json', 'utf8')); ok(Object.keys(proj.moved).length > 1 && proj.gedcom.length > 1000 && proj.v === 2, `project saved (${Object.keys(proj.moved).length} moved cards, gedcom embedded)`);
const saved = await tf();
await pg.reload(); await pg.setInputFiles('#proj', '/tmp/proj.json'); await pg.waitForSelector('.card');
ok(JSON.stringify(await tf()) === JSON.stringify(saved), 'reopened project restores all positions');
ok(errs.length === 0, 'no page errors ' + errs.join(';'));
await b.close();
